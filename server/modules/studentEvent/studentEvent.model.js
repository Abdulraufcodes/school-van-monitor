
import mongoose from 'mongoose';

const { Schema, model, models } = mongoose;

const studentEventSchema = new Schema(
  {
    schoolId: {
      type: Schema.Types.ObjectId,
      ref: 'School',
      required: true,
      index: true
    },
    studentId: {
      type: Schema.Types.ObjectId,
      ref: 'Student',
      required: true
    },
    tripId: {
      type: Schema.Types.ObjectId,
      ref: 'Trip',
      required: true
    },
    vanId: {
      type: Schema.Types.ObjectId,
      ref: 'Van',
      required: true
    },
    serviceDate: {
      type: String,
      required: true,
      match: /^\d{4}-\d{2}-\d{2}$/
    },
    driverId: {
      type: Schema.Types.ObjectId,
      ref: 'User',
      required: true
    },
    type: {
      type: String,
      enum: ['picked_up', 'dropped_off'],
      required: true
    },
    // Official timestamp is always generated by the server.
    occurredAt: {
      type: Date,
      required: true,
      default: Date.now
    },
    // Optional device timestamp for auditing only.
    recordedAt: {
      type: Date,
      default: null
    },
    notes: {
      type: String,
      trim: true,
      maxlength: 200,
      default: null
    }
  },
  { timestamps: true }
);

// Prevent duplicate pickup or drop-off events for a student on one trip.
studentEventSchema.index(
  { tripId: 1, studentId: 1, type: 1 },
  { unique: true }
);

studentEventSchema.index({ studentId: 1, occurredAt: -1 });
studentEventSchema.index({ tripId: 1, occurredAt: -1 });

studentEventSchema.index(
  { schoolId: 1, studentId: 1, serviceDate: 1, type: 1 },
  {
    unique: true,
    partialFilterExpression: { serviceDate: { $type: 'string' } }
  }
);

const StudentEvent =
  models.StudentEvent || model('StudentEvent', studentEventSchema);

export default StudentEvent;
